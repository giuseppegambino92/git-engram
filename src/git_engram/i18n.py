_current = DEFAULT_LANG


def normalize_lang(value: str | None) -> str | None:
    """Map ``"it"``, ``"IT"``, ``"it_IT.UTF-8"`` or ``"it-IT"`` to a supported code; ``None`` if unsupported."""
    if not value:
        return None
    code = value.strip().lower().replace("-", "_").split(".", 1)[0].split("_", 1)[0]
    return code if code in SUPPORTED_LANGS else None


def resolve_lang(cli_value: str | None = None) -> str:
    """Language precedence: explicit CLI value, then ``$GIT_ENGRAM_LANG``, then English."""
    return normalize_lang(cli_value) or normalize_lang(os.environ.get(ENV_VAR)) or DEFAULT_LANG


def set_lang(lang: str | None) -> str:
    """Set the process-wide language (unsupported values fall back to English) and return it."""
    global _current
    _current = normalize_lang(lang) or DEFAULT_LANG
    return _current


def get_lang() -> str:
    return _current


def translate(lang: str, key: str, /, **kwargs: object) -> str:
    """Message ``key`` in ``lang`` (English if the language lacks it), formatted with ``kwargs``."""
    catalog = MESSAGES.get(normalize_lang(lang) or DEFAULT_LANG, MESSAGES[DEFAULT_LANG])
    template = catalog.get(key)
    if template is None:
        template = MESSAGES[DEFAULT_LANG][key]  # unknown keys are a bug: raise KeyError
    return template.format(**kwargs)


def t(key: str, /, **kwargs: object) -> str:
    """Message ``key`` in the current language."""
    return translate(_current, key, **kwargs)


def placeholders(template: str) -> set[str]:
    """Names of the ``str.format`` fields used by a catalog entry."""
    return {name for _, name, _, _ in Formatter().parse(template) if name is not None}
